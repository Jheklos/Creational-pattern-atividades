public class ConfiguracaoErrada {

    private String idioma;
    private String tema;

    // Construtor público
    public ConfiguracaoErrada() {
    }

    public String getIdioma() {
        return idioma;
    }

    public void setIdioma(String idioma) {
        this.idioma = idioma;
    }

    public String getTema() {
        return tema;
    }

    public void setTema(String tema) {
        this.tema = tema;
    }
}